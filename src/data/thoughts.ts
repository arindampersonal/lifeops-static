/**
 * Get today's thought. Falls back to the most recent thought if today has none.
 */
export function getTodaysThought(): ThoughtOfTheDay {
  const today = new Date().toISOString().split('T')[0]
  const todaysThought = thoughts.find((t) => t.date === today)
  return todaysThought || thoughts[0]
}

/**
 * Get a thought by its date string (YYYY-MM-DD).
 */
export function getThoughtByDate(date: string): ThoughtOfTheDay | undefined {
  return thoughts.find((t) => t.date === date)
}
